-- Hairline colorscheme: the hairline design system's tokens mapped onto nvim
-- highlight groups, so the editor matches wezterm and herdr.
-- Follows 'background'; nvim reloads a loaded colorscheme when it changes,
-- so this file must never set 'background' itself.
-- Hairline rules carried over: hairlines instead of tinted panels, no weight
-- above medium (bold is kept to a few headings), --cat-* for syntax.
package.loaded['hairline.palette'] = nil
local c = require('hairline.palette').get()

vim.cmd 'highlight clear'
if vim.fn.exists 'syntax_on' == 1 then
  vim.cmd 'syntax reset'
end
vim.g.colors_name = 'hairline'

for i, color in ipairs(c.terminal) do
  vim.g['terminal_color_' .. (i - 1)] = color
end

